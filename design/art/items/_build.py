def check_grid(rows: list[str]) -> None:
    """격자가 16×16 인가.

    한 줄이라도 어긋나면 그림이 밀리는데, SVG 로 구운 뒤에는 그것이 안 보인다.

    Args:
        rows: 격자 줄들.

    Raises:
        ValueError: 줄 수·칸 수가 다르거나 팔레트에 없는 글자가 섞인 경우.
    """
    if len(rows) != GRID:
        raise ValueError(f"줄이 {len(rows)} 이다")
    for at, row in enumerate(rows):
        if len(row) != GRID:
            raise ValueError(f"{at}행이 {len(row)}칸이다: {row!r}")
        for ch in row:
            if ch != "." and ch not in PALETTE:
                raise ValueError(f"{at}행에 모르는 글자 {ch!r}")


def build_svg(rows: list[str]) -> str:
    """가로로 이어진 같은 색을 한 사각형으로 묶어 SVG 로 만든다.

    칸마다 사각형을 두면 256개가 되고, 묶으면 보통 40~80개다.

    Args:
        rows: 격자 줄들.

    Returns:
        SVG 문서 한 줄.
    """
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < GRID:
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < GRID and row[x + run] == ch:
                run += 1
            parts.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{PALETTE[ch]}"/>')
            x += run
    body = "".join(parts)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {GRID} {GRID}" '
        f'shape-rendering="crispEdges">{body}</svg>'
    )


