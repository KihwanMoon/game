"""도플갱어 — 빌드를 든 정예 (결정 #35·#02 위에 선다).

**정예를 세게 만든 것이 아니라 살아 있게 만든 것이다.** 도플갱어는 플레이어 형태의
로드아웃과 플레이어 규칙표를 들고 선다. 5층에서 만나는 도플갱어는 「운 좋게 레벨이 오른
것」이 아니라 **거기까지 실제로 내려간 빌드**다 — 봇이 죽은 그 층에 그 봇의 것으로 선다.

**스스로 내려가지는 않는다.** 한때 이 자리에 「세계 틱마다 하강을 한다」고 적혀 있었는데
그런 코드는 없었다. 층은 설 때 정해지고 그대로다; 움직이는 것은 레벨뿐이다 — 만나면
크고(`add_monster_xp`) 잡히면 감쇠한다(`apply_monster_defeat`). 깊이가 갱신되는 길은
**더 깊은 데서 죽은 새 봇이 자리를 밀어내는 것**이다 (`MAX_DOPPELS`).

그 빌드는 봇이 남긴 것이다. 봇이 깊은 층에서 죽으면 그 자리에 그림자가 선다 — 이름값이
여기서 생긴다. 실제 플레이어의 규칙표를 복사하지 않으므로 공개 문제도 없다.

**전리품을 만들지 않는다.** 이것이 이 모듈의 두 번째 이유다. 도플갱어는 봇의 장비에서
나오므로, 잡았을 때 무엇이든 떨어지면 **봇이 벌어 둔 것을 사람에게 건네는 통로**가 된다 —
아이템이 세계에 들어오는 문은 검증된 런 하나뿐이라는 결정 #02 가 그 자리에서 뚫린다.
봇을 여럿 돌려 죽이는 것이 최적 파밍이 되는 것도 같은 구멍이다 (T11).

막는 자리를 셋으로 둔다. 드롭 굴림, 전리품 강탈, 되찾기 — 아이템이 도플갱어를 거쳐
사람에게 갈 수 있는 길이 그 셋뿐이다.
"""

# 도플갱어의 카탈로그 id. **제 종을 갖는다** — 종이 따로여야 드롭 표·도감·처치 통계가
# 전부 기존 기제 위에서 갈린다. 슬롯 이름으로 가르면 그 기제마다 예외를 심어야 한다.
from game.schemas.monster_snapshot import DOPPEL_SLOT_PREFIX

DOPPEL_KIND_ID = "doppelganger"

# 자리 이름 머리는 **스키마의 것을 쓴다.** 코어가 이 머리로 「더해야 하는 개체」를
# 가르므로, 두 곳에 적으면 한쪽만 고쳐졌을 때 그림자가 안 서거나 남이 더해진다.

# 세계에 둘 도플갱어 수 (개정 2026-09-04, 5 → 20).
#
# **자리가 아니라 순위표다.** 예전에는 선착순 다섯이었고 비우는 길이 없었다 — 자리가
# 차는 순간 그 뒤의 모든 죽음이 조용히 버려졌다. 실제로 그렇게 굳었다: 자리 다섯이
# 하루 만에 **전부 2층 그림자**로 차고(2층 죽음이 가장 흔하다) 그 뒤 1,170판이 통째로
# 버려졌다. 3층 이상에서 죽은 84판도 함께 버려졌으니, 「거기까지 실제로 내려간 빌드」라는
# 이 모듈의 전제와 **정반대**로 돌고 있었다.
#
# 그래서 상한의 뜻이 바뀌었다. 이제 이것은 「몇이 넘으면 버린다」가 아니라 **「가장 깊은
# 몇을 남긴다」**이고(`create_doppel`), 그래서 숫자가 커져도 세계가 그림자로 덮이지
# 않는다 — 얕은 것은 애초에 자리를 못 지킨다. 사람이 잡으면 자리가 비므로 스물이 늘
# 차 있지도 않다.
MAX_DOPPELS = 20

# 이 층보다 얕은 곳에서 죽은 봇은 그림자를 남기지 않는다. 1층에서 죽은 빌드가 서면
# 도플갱어가 「못 하는 것들의 모임」이 된다.
MIN_DOPPEL_FLOOR = 2

# 그림자가 견디는 처치 횟수 (개정 2026-09-04).
#
# **한 번 잡았다고 사라지지 않는다.** 처치가 자리를 비우게 한 직후에 나온 문제다: 봇들이
# 쉼 없이 싸우니 그림자가 서자마자 지워져 사람이 만날 새가 없었다. 그렇다고 안 지우면
# 자리가 굳는다 — 그것이 원래 고치려던 병이다.
#
# 셋이 그 사이를 잡는다. 잡을 때마다 하나 줄고 **레벨도 함께 감쇠하므로**, 같은 그림자를
# 세 번 만나되 만날 때마다 약해진다. 「끝내 지웠다」가 한 판이 아니라 이야기가 된다.
DOPPEL_LIVES = 3


def check_is_doppel(kind_id: str) -> bool:
    """이 종이 도플갱어인가.

    아이템이 도플갱어를 거쳐 사람에게 가는 길목마다 이것을 묻는다. 드롭 표를 비워 두는
    것으로 대신하지 않는 이유는, 비어 있는 표는 **나중에 누가 채울 수 있는 데이터**이고
    이것은 채울 수 없는 **코드**이기 때문이다.

    Args:
        kind_id: 볼 종 id.

    Returns:
        도플갱어면 참.
    """
    return kind_id == DOPPEL_KIND_ID


def build_doppel_slot(record_id: int) -> str:
    """도플갱어의 자리 이름을 짓는다.

    Args:
        record_id: 개체 기록 id.

    Returns:
        `doppel_12` 꼴. 방 템플릿의 슬롯과 겹치지 않는다.
    """
    return f"{DOPPEL_SLOT_PREFIX}{record_id}"
