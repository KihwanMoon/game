"""도플갱어 — 빌드를 든 정예 (결정 #35·#02 위에 선다).

**정예를 세게 만든 것이 아니라 살아 있게 만든 것이다.** 도플갱어는 플레이어 형태의
로드아웃과 플레이어 규칙표를 들고 선다. 5층에서 만나는 도플갱어는 「운 좋게 레벨이 오른
것」이 아니라 **거기까지 실제로 내려간 빌드**다 — 봇이 죽은 그 층에 그 봇의 것으로 선다.

**스스로 내려가지는 않는다.** 한때 이 자리에 「세계 틱마다 하강을 한다」고 적혀 있었는데
그런 코드는 없었다. 층은 설 때 정해지고 그대로다; 움직이는 것은 레벨뿐이다 — 만나면
크고(`add_monster_xp`) 잡히면 감쇠한다(`apply_monster_defeat`). 깊이가 갱신되는 길은
**그 층에서 새로 죽은 봇이 그 층의 오래된 그림자를 밀어내는 것**이다 (`MAX_DOPPELS_PER_FLOOR`).

그 빌드는 봇이 남긴 것이다. 봇이 깊은 층에서 죽으면 그 자리에 그림자가 선다 — 이름값이
여기서 생긴다. 실제 플레이어의 규칙표를 복사하지 않으므로 공개 문제도 없다.

**전리품을 만들지 않는다.** 이것이 이 모듈의 두 번째 이유다. 도플갱어는 봇의 장비에서
나오므로, 잡았을 때 무엇이든 떨어지면 **봇이 벌어 둔 것을 사람에게 건네는 통로**가 된다 —
아이템이 세계에 들어오는 문은 검증된 런 하나뿐이라는 결정 #02 가 그 자리에서 뚫린다.
봇을 여럿 돌려 죽이는 것이 최적 파밍이 되는 것도 같은 구멍이다 (T11).

막는 자리를 셋으로 둔다. 드롭 굴림, 전리품 강탈, 되찾기 — 아이템이 도플갱어를 거쳐
사람에게 갈 수 있는 길이 그 셋뿐이다.
"""

# 도플갱어의 카탈로그 id. **제 종을 갖는다** — 종이 따로여야 드롭 표·도감·처치 통계가
# 전부 기존 기제 위에서 갈린다. 슬롯 이름으로 가르면 그 기제마다 예외를 심어야 한다.
from game.schemas.monster_snapshot import DOPPEL_SLOT_PREFIX

DOPPEL_KIND_ID = "doppelganger"

# 자리 이름 머리는 **스키마의 것을 쓴다.** 코어가 이 머리로 「더해야 하는 개체」를
# 가르므로, 두 곳에 적으면 한쪽만 고쳐졌을 때 그림자가 안 서거나 남이 더해진다.

# 한 장에 설 수 있는 그림자 수 (개정 2026-09-15).
#
# **세는 단위는 장이지 세계가 아니다.** 전체 상한 하나로만 재던 때는 그 상한이 「가장 깊은
# 스물을 남긴다」로 돌았고, 실측으로 **스물 중 열아홉이 9장에 몰렸다** — 주인은 셋뿐이었다.
# 9장에 닿은 사람은 다섯 방이 전부 그림자였고 2~8장에서는 하나도 못 만났다. 깊이로 줄을
# 세우면 얕은 장이 영원히 진다.
#
# **둘인 이유는 방 수다.** `doppel_pick.build_room_doppels` 가 **방 하나에 그림자 하나씩**
# 세우고 한 장은 방 다섯을 돈다(`tickets.CHAIN_LENGTH`). 그래서 그 장의 그림자 수가 곧
# 「다섯 방 중 몇 방에서 만나는가」다 — 둘이면 5방 중 2방이고, 아래 `DOPPELS_PER_SOURCE`
# 가 그 둘을 **서로 다른 사람의 빌드**로 만든다. 다섯으로 두면 모든 방이 그림자가 된다.
MAX_DOPPELS_PER_FLOOR = 2

# 원천 하나가 세계에 세울 수 있는 그림자 수 (신설 2026-09-15).
#
# **비례를 전체 상한이 아니라 여기에 건다.** 「세계에 스물」처럼 총량에만 걸면 다양성이
# 안 지켜진다 — 계정 **둘**이 각자 아홉 장을 하나씩 차지하면 장 정원이 그대로 차기
# 때문이다. 실측이 그 모양이었다: 그림자 스물의 주인이 세 계정뿐이었다.
#
# 한 사람이 둘까지만 세우면 세계 상한은 **원천 수 × 2 로 저절로 따라온다**
# (`compute_doppel_cap`). 사람이 셋인 세계는 그림자가 여섯이지 열여덟이 아니다.
#
# 여기서 원천은 **그림자를 세울 수 있는 계정**이다 — 봇이거나, 동의를 켠 사람
# (`check_doppel_opt_in`). 판을 안 내는 계정까지 세면 상한이 허수가 된다.
#
# **둘인 이유**: 하나면 그 사람의 「가장 최근 죽음」만 남아 빌드 하나가 곧 사람 하나가
# 된다 — 얕게도 깊게도 가 본 사람이 둘 중 하나를 잃는다. 셋이면 원천이 적을 때 한 사람이
# 세계의 셋 중 하나를 차지한다. 넘치면 **제 것 중 가장 오래된 것**이 물러난다.
DOPPELS_PER_SOURCE = 2

# 이 층보다 얕은 곳에서 죽은 봇은 그림자를 남기지 않는다. 1층에서 죽은 빌드가 서면
# 도플갱어가 「못 하는 것들의 모임」이 된다.
MIN_DOPPEL_FLOOR = 2

# 그림자가 견디는 처치 횟수 (개정 2026-09-04).
#
# **한 번 잡았다고 사라지지 않는다.** 처치가 자리를 비우게 한 직후에 나온 문제다: 봇들이
# 쉼 없이 싸우니 그림자가 서자마자 지워져 사람이 만날 새가 없었다. 그렇다고 안 지우면
# 자리가 굳는다 — 그것이 원래 고치려던 병이다.
#
# 셋이 그 사이를 잡는다. 잡을 때마다 하나 줄고 **레벨도 함께 감쇠하므로**, 같은 그림자를
# 세 번 만나되 만날 때마다 약해진다. 「끝내 지웠다」가 한 판이 아니라 이야기가 된다.
DOPPEL_LIVES = 3


def check_is_doppel(kind_id: str) -> bool:
    """이 종이 도플갱어인가.

    아이템이 도플갱어를 거쳐 사람에게 가는 길목마다 이것을 묻는다. 드롭 표를 비워 두는
    것으로 대신하지 않는 이유는, 비어 있는 표는 **나중에 누가 채울 수 있는 데이터**이고
    이것은 채울 수 없는 **코드**이기 때문이다.

    Args:
        kind_id: 볼 종 id.

    Returns:
        도플갱어면 참.
    """
    return kind_id == DOPPEL_KIND_ID


def build_doppel_slot(record_id: int) -> str:
    """도플갱어의 자리 이름을 짓는다.

    Args:
        record_id: 개체 기록 id.

    Returns:
        `doppel_12` 꼴. 방 템플릿의 슬롯과 겹치지 않는다.
    """
    return f"{DOPPEL_SLOT_PREFIX}{record_id}"


def compute_doppel_cap(source_count: int) -> int:
    """원천 수에서 세계의 그림자 상한을 낸다.

    **이것은 따로 거는 규칙이 아니라 `DOPPELS_PER_SOURCE` 의 결과다.** 한 사람이 둘까지만
    세우므로 총량이 저절로 이 값을 넘지 않는다. 그래도 `create_doppel` 이 마지막에 한 번
    더 재는 것은, 앞으로 그림자를 세우는 길이 하나 더 생겼을 때 그 길이 이 상한을 조용히
    비껴가지 못하게 하기 위해서다.

    **비례가 지키는 것은 밀도가 아니라 다양성이다.** 장 정원(`MAX_DOPPELS_PER_FLOOR`)이
    이미 「한 장에 몇」을 막으므로, 이쪽이 막는 것은 **적은 사람의 빌드가 세계를 채우는
    것**이다. 실측으로 계정 셋이 그림자 스물을 쥐고 있었다 (2026-09-15).

    Args:
        source_count: 그림자를 세울 수 있는 계정 수 (봇 + 동의한 사람).

    Returns:
        지금 세계가 담을 수 있는 그림자 수. 원천이 없으면 0.
    """
    return max(0, source_count) * DOPPELS_PER_SOURCE
