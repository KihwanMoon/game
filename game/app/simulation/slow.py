"""둔화가 무엇을 늦추는가 (GDD §211).

`actions.py` 에서 갈라 나왔다. 저쪽은 **무엇을 하는가**(실행기)이고 여기는 **이번 틱에
할 수 있는가**다. 파일이 400줄 상한을 넘은 것이 계기였을 뿐, 가르는 선은 책임이다 (§4).

**이동만이 아니라 행동 전체를 늦춘다 (2026-09-10 결정).** 예전에는 이동 경로에서만
봤고, 그래서 `SLOW` 는 **안 움직여도 때리는 사격형에게 아무 효과가 없었다** — 이미
붙은 돌진형에게도 없었다. 서리 장판이 피해 0 으로는 어느 표에서도 값을 못 한 원인이
그것이고(설계/5_스킬 §10.10), 그때는 스킬에 피해를 줘서 우회했다. 이 파일이 그 우회를
되돌리는 자리다.

**몬스터가 거는 둔화도 함께 세진다.** 플레이어가 맞는 쪽도 두 배로 아파지므로, 자폭형·
사격형의 균형은 이 변경 뒤에 다시 재야 한다.
"""

from game.app.simulation.plan import SLOW_EVERY, STATUS_SLOW
from game.app.simulation.state import Entity


def check_slowed_this_tick(entity: Entity, tick: int) -> bool:
    """둔화 때문에 이번 틱을 쉬는가.

    **둔화는 두 틱에 한 번이다** (GDD §211 의 「이동 2틱 소모」). 없으면 `SLOW` 는 인지
    변수에만 있고 걸어도 아무 일이 없다 — 상태를 거는 스킬이 빈 껍데기가 되는 자리다.

    **틱의 홀짝으로 가른다.** 걸린 시점을 따로 들고 있으면 그것이 세계 상태가 되고 두
    코어가 그 값을 함께 얼려야 한다. 홀짝은 이미 있는 값이라 그럴 필요가 없다 (R5).

    Args:
        entity: 행동하려는 엔티티.
        tick: 지금 틱.

    Returns:
        쉬는 틱이면 True.
    """
    return entity.statuses.get(STATUS_SLOW, 0) > 0 and tick % SLOW_EVERY != 0
