/**
 * 도면 격자 칸의 **겉면** — 무엇이 그려지는가 (도면 그리드).
 *
 * 가방·장비가 먼저 이 모양을 썼고, 소모품 칸과 경매장이 같은 질문("이게 뭐고 어느 게
 * 더 좋은가")에 답하게 되면서 셋이 같은 겉면을 나눠 쓴다. **겉면과 알맹이를 가르는
 * 이유**는 알맹이가 화면마다 다르기 때문이다 — 가방 칸은 `SlotView` 를, 소모품 칸은
 * 칸이나 재고를, 경매 칸은 매물을 가리킨다. 겉면까지 셋으로 갈리면 같은 것이 세 모양으로
 * 그려지고, 그때부터 한 화면을 고쳐도 나머지 둘은 옛 모양으로 남는다 (봇 가방이 유저
 * 가방과 다른 목록이던 것이 그 병이었다).
 *
 * 순수 타입이다. 렌더는 `GridCellView` 가 한다.
 */

/** 격자 칸의 겉면. 칸에 그려지는 것 전부이며, 무엇을 가리키는지는 모른다. */
export interface CellFace {
  /** React key 이자 선택 식별자. 화면마다 접두사를 달리 붙인다. */
  readonly key: string
  /** 칸 구석의 도식 코드. 부위·쓰임새처럼 **자리**를 말한다. */
  readonly code: string
  /** 칸 가운데 글자. 비었으면 빈 문자열이다. */
  readonly label: string
  readonly grade: string
  /** 칸의 상태 글리프들 (파손 ◈, 봉인 ◇n, 귀속 ▨, 양손 점유 ▨). */
  readonly marks: readonly string[]
  /** 오른쪽 아래 수치. 개수(`x3`)나 충전(`2/4`)처럼 **양**을 말한다. */
  readonly countText: string
  /**
   * 이 물건이 **무엇을 해 주는가** 한 줄.
   *
   * 이것이 없으면 격자를 봐서는 어느 게 더 좋은지 알 수 없어 칸을 하나씩 눌러야 한다 —
   * 방 드롭다운이 영문 id 서른한 줄이던 것과 같은 병이다. 접사를 전부 적지 않는 이유는
   * 칸마다 줄 수가 달라지면 격자가 들쭉날쭉해 눈이 세로로 못 가기 때문이다.
   */
  readonly fact: string
  /** 쓸 수 없게 막힌 칸인가 (양손무기가 점유한 자리 등). */
  readonly isSealedSlot: boolean
}
